export function getFeatureMetadata(name) {
  for (const group of FEATURE_GROUPS) {
    const found = group.features.find((f) => f.name === name);
    if (found) {
      return { ...found, groupTitle: group.title, groupColor: group.color };
    }
  }
  return { name, unit: "", desc: "Network flow feature", groupTitle: "General", groupColor: "#2878FF" };
}
